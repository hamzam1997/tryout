import { useEffect, useState } from "react";
import Icon from "./Icon";

const TABS = [
  { id: "modules", label: "Modules" },
  { id: "models", label: "Data models" },
  { id: "routes", label: "API routes" },
  { id: "integrations", label: "Integrations" },
  { id: "guidelines", label: "Ownership & rules" },
];

export default function ArchitectureCatalogDrawer({ repository, catalog, onClose }) {
  const [activeTab, setActiveTab] = useState("modules");

  useEffect(() => {
    function handleKeyDown(e) {
      if (e.key === "Escape") onClose();
    }
    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, [onClose]);

  if (!catalog) return null;

  const modules = catalog.modules || [];
  const models = catalog.internal_models || [];
  const routes = catalog.api_routes || [];
  const integrations = catalog.external_integrations || [];
  const dependencies = catalog.external_dependencies || [];
  const configKeys = catalog.config_keys || [];
  const codeowners = catalog.codeowners || {};
  const guidelines = catalog.coding_guidelines || [];

  return (
    <div className="drawer-overlay" onClick={onClose} role="dialog" aria-modal="true" aria-label="Architecture catalog">
      <div className="drawer-card" onClick={(e) => e.stopPropagation()}>
        {/* Drawer Header */}
        <div className="drawer-head">
          <div>
            <div className="drawer-title-row">
              <h2>{catalog.name || repository?.name || "Architecture Catalog"}</h2>
              <span className="badge badge-info">{catalog.language || "Unknown language"}</span>
              {catalog.framework && <span className="badge badge-idle">{catalog.framework}</span>}
            </div>
            <p className="drawer-sub">
              {(repository?.source || "Repository").replace("https://github.com/", "")} · Catalog generated by Gemini 2.5 Flash
            </p>
          </div>
          <button type="button" className="icon-btn drawer-close" onClick={onClose} aria-label="Close catalog">
            <Icon name="close" />
          </button>
        </div>

        {/* Quick Specs Strip */}
        <div className="catalog-specs-strip">
          {catalog.entrypoint && (
            <div className="spec-item">
              <span className="spec-label">Entrypoint</span>
              <code>{catalog.entrypoint}</code>
            </div>
          )}
          {catalog.test_command && (
            <div className="spec-item">
              <span className="spec-label">Test command</span>
              <code>{catalog.test_command}</code>
            </div>
          )}
          <div className="spec-item">
            <span className="spec-label">Subsystems</span>
            <span>{modules.length} modules</span>
          </div>
          <div className="spec-item">
            <span className="spec-label">Endpoints</span>
            <span>{routes.length} routes</span>
          </div>
        </div>

        {/* Summary note if present */}
        {catalog.summary && (
          <div className="catalog-summary-box">
            <p>{catalog.summary}</p>
          </div>
        )}

        {/* Tab Switcher */}
        <div className="drawer-tabs" role="tablist">
          {TABS.map((tab) => (
            <button
              key={tab.id}
              type="button"
              className={`drawer-tab ${activeTab === tab.id ? "is-active" : ""}`}
              role="tab"
              aria-selected={activeTab === tab.id}
              onClick={() => setActiveTab(tab.id)}
            >
              {tab.label}
            </button>
          ))}
        </div>

        {/* Tab Content */}
        <div className="drawer-body">
          {activeTab === "modules" && (
            <div className="catalog-section">
              {modules.length === 0 ? (
                <p className="empty-subtext">No distinct subsystems extracted.</p>
              ) : (
                <div className="modules-grid">
                  {modules.map((mod, i) => (
                    <div key={i} className="module-card">
                      <div className="module-card-head">
                        <h3>{mod.name}</h3>
                        {mod.owner && <span className="badge badge-owner">{mod.owner}</span>}
                      </div>
                      <p className="module-path"><code>{mod.path}</code></p>
                      <p className="module-desc">{mod.description}</p>
                      {mod.responsibilities?.length > 0 && (
                        <div className="module-responsibilities">
                          <span className="mini-label">Responsibilities</span>
                          <ul>
                            {mod.responsibilities.map((r, ri) => (
                              <li key={ri}>{r}</li>
                            ))}
                          </ul>
                        </div>
                      )}
                      {mod.key_files?.length > 0 && (
                        <div className="module-files">
                          {mod.key_files.map((kf, kfi) => (
                            <code key={kfi} className="file-chip">{kf}</code>
                          ))}
                        </div>
                      )}
                    </div>
                  ))}
                </div>
              )}
            </div>
          )}

          {activeTab === "models" && (
            <div className="catalog-section">
              {models.length === 0 ? (
                <p className="empty-subtext">No data models detected.</p>
              ) : (
                <div className="models-list">
                  {models.map((model, i) => (
                    <div key={i} className="model-row">
                      <div className="model-row-head">
                        <span className="model-name">{model.name}</span>
                        {model.file_path && <code className="model-file">{model.file_path}</code>}
                      </div>
                      {model.description && <p className="model-desc">{model.description}</p>}
                      {model.fields?.length > 0 && (
                        <div className="model-fields">
                          {model.fields.map((f, fi) => (
                            <span key={fi} className="field-chip">{f}</span>
                          ))}
                        </div>
                      )}
                    </div>
                  ))}
                </div>
              )}
            </div>
          )}

          {activeTab === "routes" && (
            <div className="catalog-section">
              {routes.length === 0 ? (
                <p className="empty-subtext">No API routes detected.</p>
              ) : (
                <div className="routes-list">
                  {routes.map((route, i) => {
                    const method = (route.method || "GET").toUpperCase();
                    return (
                      <div key={i} className="route-row">
                        <span className={`method-chip method-${method.toLowerCase()}`}>{method}</span>
                        <code className="route-path">{route.path}</code>
                        {route.handler && <code className="route-handler">{route.handler}()</code>}
                        {route.file_path && <span className="route-file">{route.file_path}</span>}
                        {route.description && <p className="route-desc">{route.description}</p>}
                      </div>
                    );
                  })}
                </div>
              )}
            </div>
          )}

          {activeTab === "integrations" && (
            <div className="catalog-section">
              <h3 className="catalog-heading">Adapters and gateways</h3>
              {integrations.length === 0 ? (
                <p className="empty-subtext">No external services integrated in-repo.</p>
              ) : (
                <div className="integrations-list">
                  {integrations.map((integ, i) => (
                    <div key={i} className="integration-card">
                      <div className="integration-head">
                        <strong>{integ.name}</strong>
                        {integ.file_path && <code>{integ.file_path}</code>}
                      </div>
                      <p>{integ.description}</p>
                      {integ.auth && <p className="integration-meta"><span className="mini-label">Auth</span> {integ.auth}</p>}
                      {integ.env_keys?.length > 0 && (
                        <div className="integration-keys">
                          <span className="mini-label">Env</span>
                          {integ.env_keys.map((k, ki) => (
                            <code key={ki}>{k}</code>
                          ))}
                        </div>
                      )}
                    </div>
                  ))}
                </div>
              )}

              {dependencies.length > 0 && (
                <div className="deps-section">
                  <h3 className="catalog-heading">Service dependencies</h3>
                  <div className="deps-chips">
                    {dependencies.map((dep, di) => (
                      <span key={di} className="chip">{dep}</span>
                    ))}
                  </div>
                </div>
              )}

              {configKeys.length > 0 && (
                <div className="config-section">
                  <h3 className="catalog-heading">Configuration</h3>
                  <div className="config-grid">
                    {configKeys.map((cfg, ci) => (
                      <div key={ci} className="config-item">
                        <code>{cfg.name}</code>
                        {cfg.required && <span className="badge badge-warn">Required</span>}
                        {cfg.description && <p>{cfg.description}</p>}
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </div>
          )}

          {activeTab === "guidelines" && (
            <div className="catalog-section">
              {Object.keys(codeowners).length > 0 && (
                <div className="codeowners-section">
                  <h3 className="catalog-heading">Code owners</h3>
                  <div className="codeowners-table">
                    {Object.entries(codeowners).map(([pattern, owner], i) => (
                      <div key={i} className="codeowner-row">
                        <code>{pattern}</code>
                        <span className="badge badge-owner">{owner}</span>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {guidelines.length > 0 && (
                <div className="guidelines-section">
                  <h3 className="catalog-heading">Conventions</h3>
                  <ul className="guidelines-list">
                    {guidelines.map((g, gi) => (
                      <li key={gi}>{g}</li>
                    ))}
                  </ul>
                </div>
              )}
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
